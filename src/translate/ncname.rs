/// Whether `name` is an XML 1.0 `NCName`, and so can be written into an
/// XPath expression as a namespace prefix.
pub(crate) fn is_ncname(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    is_name_start(first) && chars.all(is_name_char)
}

/// The `(Letter | '_')` a name has to begin with.
fn is_name_start(c: char) -> bool {
    if c.is_ascii() {
        return c.is_ascii_alphabetic() || c == '_';
    }
    in_table(c, LETTERS)
}

/// `NameChar` minus the colon: a start character, or one of the
/// combining marks, digits, extenders, `.` and `-` that may only follow.
fn is_name_char(c: char) -> bool {
    if c.is_ascii() {
        return c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | '-');
    }
    in_table(c, LETTERS) || in_table(c, TRAILING)
}

fn in_table(c: char, table: &[(u32, u32)]) -> bool {
    let c = c as u32;
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                Ordering::Less
            } else if lo > c {
                Ordering::Greater
            } else {
                Ordering::Equal
            }
        })
        .is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ascii_names() {
        assert!(is_ncname("div"));
        assert!(is_ncname("_x"));
        assert!(is_ncname("a-b.c_1"));
        assert!(!is_ncname(""));
        assert!(!is_ncname("1a"));
        assert!(!is_ncname("-a"));
        assert!(!is_ncname(".a"));
        assert!(!is_ncname("di[v"));
        assert!(!is_ncname("a b"));
        // A prefix is exactly one name: the colon that joins it to a
        // local part is not part of it.
        assert!(!is_ncname("a:b"));
    }

    #[test]
    fn non_ascii_names() {
        assert!(is_ncname("nsé"));
        assert!(is_ncname("é"));
        assert!(is_ncname("Ελληνικά"));
        assert!(is_ncname("русский"));
        assert!(is_ncname("中文"));
        // U+00B7 MIDDLE DOT is an Extender, so it may follow but not
        // lead; U+0301 COMBINING ACUTE ACCENT is a CombiningChar and
        // behaves the same way.
        assert!(is_ncname("a·b"));
        assert!(!is_ncname("·a"));
        assert!(is_ncname("a\u{301}"));
        assert!(!is_ncname("\u{301}a"));
        // U+00A0 NO-BREAK SPACE is in none of the tables, and neither
        // is U+0242, which only the Fifth Edition tables added.
        assert!(!is_ncname("di\u{a0}v"));
        assert!(!is_ncname("ns\u{242}"));
        // Nor is anything outside the BMP: the tables predate it.
        assert!(!is_ncname("\u{10330}"));
    }

    /// Both tables are sorted, disjoint and non-adjacent — what the
    /// binary search in `in_table` assumes, and what keeps each range a
    /// canonical one rather than a split of its neighbour.
    #[test]
    fn tables_are_sorted_and_disjoint() {
        for table in [LETTERS, TRAILING] {
            for pair in table.windows(2) {
                let ((lo, hi), (next_lo, _)) = (pair[0], pair[1]);
                assert!(lo <= hi, "range {lo:#X}-{hi:#X} is inverted");
                assert!(
                    hi + 1 < next_lo,
                    "range {lo:#X}-{hi:#X} touches {next_lo:#X}"
                );
            }
        }
        // The two tables partition their characters, so a trailing-only
        // character is never also a letter.
        for &(lo, hi) in TRAILING {
            for c in lo..=hi {
                let c = char::from_u32(c).expect("table holds scalar values");
                assert!(!in_table(c, LETTERS), "{c:?} is in both tables");
            }
        }
    }
}
