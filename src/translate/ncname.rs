//! The XML 1.0 `NCName` production, which is what a CSS namespace
//! prefix has to be to survive into the XPath this crate emits.
//!
//! A namespace prefix is passed through into a node test (`svg|rect`
//! becomes `svg:rect`) because XPath 1.0 has no way to resolve one
//! without the namespace URI, which this crate never sees. So a prefix
//! that cannot be written as an XPath name has nowhere to go and errors,
//! and the predicate here is what decides which those are. Local names
//! need no such test: one that cannot be a name test folds into a
//! `local-name()` comparison instead, so they stay on the deliberately
//! conservative ASCII-only [`is_safe_name`].
//!
//! [`is_safe_name`]: super::xpath_expr::is_safe_name
//!
//! # Which `NCName`
//!
//! An XPath 1.0 `NCName` is an XML 1.0 `Name` without a colon, and XML
//! 1.0 defined `Name` by the character tables in its Appendix B:
//! `Letter` (`BaseChar | Ideographic`), `Digit`, `CombiningChar` and
//! `Extender`. XML 1.0 Fifth Edition later replaced those tables with a
//! much broader set of ranges — but that revision is of XML, not of
//! XPath 1.0, and engines split on it. The tables below are the original
//! ones, which is both the definition XPath 1.0 cites and a subset of
//! the Fifth Edition set, so a prefix accepted here parses under either
//! reading. Concretely: libxml2 parses XPath names with the original
//! tables and rejects `nsɂ:e` (U+0242), while sxd-xpath (which the test
//! suite evaluates through) implements the Fifth Edition set and accepts
//! it. Emitting only the intersection keeps a translated prefix from
//! turning into a parse error one engine reports and the other does not.
//!
//! Erring narrow is safe in a way erring broad is not: a prefix rejected
//! here is reported as an unsupported construct, which is what every
//! non-ASCII prefix used to get, whereas one accepted here and refused
//! by the evaluator is a parse failure the caller cannot attribute.

